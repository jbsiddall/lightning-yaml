'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { NativeValues: n, createHeap } = require(path.resolve(__dirname, 'dist/runtime.js'));
const h = createHeap();
assert.equal(Object.getPrototypeOf(h), Object.prototype);
assert.equal(n.nullValue, null);
assert.equal(n.undefinedValue, undefined);
assert.equal(Object.isFrozen(n), true);
assert.throws(() => { n.nullValue = 0; }, TypeError);
assert.equal(n.isNull(h, n.undefinedValue), false);
assert.equal(n.isUndefined(h, n.nullValue), false);
assert.equal(n.isNull(h, null), true);
assert.equal(n.isUndefined(h, undefined), true);
assert.equal(n.numberFromIndex(h, 42), 42);
assert.throws(() => n.numberFromIndex(h, 1.5), RangeError);
assert.throws(() => n.numberFromIndex(h, 2147483647), RangeError);
assert.equal(n.boolValue(h, false), false);
assert.equal(n.stringValue(h, '\ud800'), '\ud800');
assert.equal(n.parseNumber(h, 'Infinity'), Infinity);
assert.equal(n.parseNumber(h, '-Infinity'), -Infinity);
assert.equal(Number.isNaN(n.parseNumber(h, 'not a number')), true);
assert.equal(Object.is(n.parseNumber(h, '-0'), -0), true);
assert.equal(n.stringifyNumber(h, -0), '0');
assert.equal(n.stringifyNumber(h, Infinity), 'Infinity');
assert.equal(n.stringifyNumber(h, NaN), 'NaN');
assert.equal(n.sameValue(h, NaN, NaN), true);
assert.equal(n.sameValue(h, -0, 0), false);

const a = n.createArray(h);
const o = n.createObject(h);
assert.equal(Object.getPrototypeOf(a), Array.prototype);
assert.equal(Object.getPrototypeOf(o), Object.prototype);
n.arrayPush(h, a, 42);
n.arrayPush(h, a, null);
n.arrayPush(h, a, undefined);
assert.equal(n.arrayLength(h, a), 3);
assert.equal(n.arrayGet(h, a, 0), 42);
assert.equal(n.arrayGet(h, a, 1), null);
assert.equal(n.arrayGet(h, a, 2), undefined);
assert.equal(Object.hasOwn(a, 2), true);
n.arraySet(h, a, 0, -0);
assert.equal(Object.is(a[0], -0), true);
assert.throws(() => n.arrayGet(h, a, 3), RangeError);
assert.throws(() => n.arraySet(h, a, 3, false), RangeError);
const sparse = [];
sparse.length = 1;
assert.throws(() => n.arrayGet(h, sparse, 0), TypeError);

n.objectSet(h, o, 'child', a);
n.objectSet(h, o, 'alias', a);
n.objectSet(h, o, 'self', o);
n.objectSet(h, o, 'missingValue', undefined);
n.objectSet(h, o, '__proto__', a);
assert.equal(o.child, a);
assert.equal(o.alias, a);
assert.equal(o.self, o);
assert.equal(o.__proto__, a);
assert.equal(Object.getPrototypeOf(o), Object.prototype);
assert.equal(n.objectHasOwn(h, o, '__proto__'), true);
assert.equal(n.objectHasOwn(h, o, 'missingValue'), true);
assert.equal(n.objectHasOwn(h, o, 'notPresent'), false);
assert.equal(n.objectGet(h, o, 'missingValue'), undefined);
assert.equal(n.objectGet(h, o, 'notPresent'), undefined);
assert.equal(n.objectGet(h, o, 'toString'), undefined);
assert.deepEqual(n.objectKeys(h, o), ['child', 'alias', 'self', 'missingValue', '__proto__']);
assert.equal(n.sameValue(h, o, o), true);
assert.equal(n.sameValue(h, o, n.createObject(h)), false);
const otherHeap = createHeap();
assert.equal(n.objectGet(otherHeap, o, 'child'), a);
assert.deepEqual(Object.keys(h), []);
console.log('Native runtime: primitives, dense arrays, own object properties, aliases/cycles passed');
